#!/usr/bin/env python3
"""Bit-exact host twin of a7ng_shared_rank_sgd_q8_sym_f2r2.sv (c3_sgd_w pipe).

Integer law KEEP: rsh40, sat16, clamp768(rsh40(acc,7)), clamp_err ±1536.
Extra RTL cycles must not change v or w. PROGRAM=NO.
"""
from __future__ import annotations

N_FEAT = 32
SHIFT_DEFAULT = 6
V_LIM = 768
ERR_LIM = 1536


def rsh40(v: int, s: int) -> int:
    if s <= 0:
        raise ValueError("rsh40 shift must be >0")
    if v == 0:
        return 0
    a = -v if v < 0 else v
    a = (a + (1 << (s - 1))) >> s
    return -a if v < 0 else a


def sat16(v: int) -> int:
    if v > 32767:
        return 32767
    if v < -32768:
        return -32768
    return int(v)


def clamp768(r: int) -> int:
    if r > V_LIM:
        return V_LIM
    if r < -V_LIM:
        return -V_LIM
    return int(r)


def clamp_err(e: int) -> int:
    if e > ERR_LIM:
        return ERR_LIM
    if e < -ERR_LIM:
        return -ERR_LIM
    return int(e)


class SharedRankSgdF2r2:
    def __init__(self, n: int = N_FEAT, shift: int = SHIFT_DEFAULT) -> None:
        self.n = n
        self.shift = shift
        self.w = [0] * n

    def reset(self) -> None:
        self.w = [0] * self.n

    def copy_w(self) -> list[int]:
        return list(self.w)

    def load_w(self, idx: int, val: int) -> None:
        self.w[idx] = sat16(val)

    def score(self, x: list[int]) -> int:
        acc = 0
        for i in range(self.n):
            acc += int(self.w[i]) * int(x[i])
        return clamp768(rsh40(acc, 7))

    def update(self, x: list[int], reward: int, freeze: bool = False) -> int:
        v = self.score(x)
        if freeze:
            return v
        err = clamp_err(int(reward) * 256 - v)
        s = 7 + self.shift
        for i in range(self.n):
            prod = err * int(x[i])
            dw40 = rsh40(prod, s)
            dw_lo = dw40 & 0xFFFF
            if dw_lo >= 0x8000:
                dw_lo -= 0x10000
            self.w[i] = sat16(self.w[i] + dw_lo)
        return v


def sv_sd16(v: int) -> str:
    if v < 0:
        return f"-16'sd{-int(v)}"
    return f"16'sd{int(v)}"


def emit_svh(path: str, vectors: dict) -> None:
    lines = ["// generated by gen_vectors.py — do not hand-edit", "`ifndef ASTRA_C3_SGD_W_EXP"]
    lines.append("`define ASTRA_C3_SGD_W_EXP")
    lines.append(f"localparam signed [15:0] EXP_V_FR = {sv_sd16(vectors['v_frozen'])};")
    lines.append(f"localparam signed [15:0] EXP_V_EN = {sv_sd16(vectors['v_enabled'])};")
    lines.append(f"localparam signed [15:0] EXP_V_SH = {sv_sd16(vectors['v_shuffle'])};")
    lines.append(f"localparam signed [15:0] EXP_V_MX = {sv_sd16(vectors['v_mixed'])};")
    mx = ", ".join(sv_sd16(w) for w in vectors["w_mixed"])
    lines.append(f"localparam signed [15:0] EXP_W_MX [0:31] = '{{{mx}}};")
    lines.append("`endif")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def main() -> None:
    x64 = [64] * N_FEAT
    frozen = SharedRankSgdF2r2()
    v_fr = frozen.score(x64)

    en = SharedRankSgdF2r2()
    for _ in range(16):
        en.update(x64, 3)
    v_en = en.score(x64)

    sh = SharedRankSgdF2r2()
    for t in range(16):
        sh.update(x64, 3 if (t & 1) else -3)
    v_sh = sh.score(x64)

    mx = SharedRankSgdF2r2()
    for i in range(N_FEAT):
        mx.load_w(i, (i * 17) - 80)
    xmix = [((i * 13) % 127) - 64 for i in range(N_FEAT)]
    v_mx = mx.update(xmix, 2)
    w_mx = mx.copy_w()

    fz = SharedRankSgdF2r2()
    for i in range(N_FEAT):
        fz.load_w(i, w_mx[i])
    w_before = fz.copy_w()
    fz.update(xmix, 3, freeze=True)
    if fz.copy_w() != w_before:
        raise SystemExit("FREEZE_W_CHANGED")

    vectors = {
        "v_frozen": v_fr,
        "v_enabled": v_en,
        "v_shuffle": v_sh,
        "v_mixed": v_mx,
        "w_mixed": w_mx,
        "w_frozen_after": w_before,
        "match_astra06_shape": (v_fr == 0),
    }
    print("ASTRA_C3_SGD_W_TWIN", vectors)
    if v_fr != 0:
        raise SystemExit("ASTRA_C3_SGD_W_TWIN_FAIL zero")
    return vectors


if __name__ == "__main__":
    vec = main()
    import os

    here = os.path.dirname(os.path.abspath(__file__))
    emit_svh(os.path.join(here, "expected.svh"), vec)
    print("ASTRA_C3_SGD_W_TWIN_PASS")
