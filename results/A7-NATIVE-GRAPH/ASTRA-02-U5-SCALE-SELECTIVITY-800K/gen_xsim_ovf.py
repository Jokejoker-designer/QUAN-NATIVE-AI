#!/usr/bin/env python3
"""Directed overflow-page XSim image. PROGRAM=NO. Actual chiller QSE keys."""
from __future__ import annotations

import json
import sys
from pathlib import Path

BAG = Path(__file__).resolve().parent
ORCH = BAG.parent / "GROK-ORCH-00"
sys.path.insert(0, str(ORCH / "U3Q-R3-STRUCTURED-QUERY-FEATURE-00"))
from twin import extract  # noqa: E402

INDEX_BASE = 0x05000000
POST_HEAP = INDEX_BASE + 0x40000
ENTRY = 16
TABLE_BYTES = 65536
EPOCH = 7
INDEX_HEAD = 32
ID_W = 20


def feat(text: str) -> dict:
    x = extract(text)
    return {
        "k": [x["k0"], x["k1"], x["k2"], x["k3"]],
        "v": [x["k0_valid"], x["k1_valid"], x["k2_valid"], x["k3_valid"]],
        "eid": x["entity_id"],
        "iid": x["intent_id"],
        "rid": x["relation_id"],
        "xid": x["context_id"],
        "text": text,
    }


def dir_addr(table: int, key: int) -> int:
    return INDEX_BASE + table * TABLE_BYTES + (key & 0xFFF) * ENTRY


def word_of(addr: int) -> int:
    return 6144 + ((addr - INDEX_BASE) >> 4)


def dir_pack(base, count, ovf, ep, ovf_base=0, ovf_count=0) -> int:
    return (
        ((ovf_count & 0xFFFF) << 108)
        | ((ovf_base & 0x0FFFFFFF) << 80)
        | ((ep & 0xFFFF) << 64)
        | ((ovf & 1) << 48)
        | ((count & 0xFFFF) << 32)
        | (base & 0x0FFFFFFF)
    )


def pack_post(ids: list[int]) -> list[int]:
    beats = []
    for i in range(0, len(ids), 4):
        chunk = ids[i : i + 4]
        v = 0
        for lane, nid in enumerate(chunk):
            v |= (nid & 0xFFFFFFFF) << (32 * lane)
        beats.append(v)
    return beats


def pack_text(s: str) -> int:
    b = s.encode("latin1")[:48]
    v = 0
    for i, x in enumerate(b):
        v |= x << (8 * i)
    return v


def main() -> int:
    q = feat("chiller")
    unk = feat("payroll tax form")
    gold = [0, 1, 2, 3]
    collide = list(range(1000, 1000 + INDEX_HEAD))
    writes = {}
    post_ptr = POST_HEAP
    # T0 and T2 (valid tables for chiller)
    for t in (0, 2):
        if q["v"][t] == 0:
            continue
        k = q["k"][t]
        head_base = post_ptr
        hb = pack_post(collide)
        for i, beat in enumerate(hb):
            writes[word_of(head_base + i * ENTRY)] = beat
        post_ptr += len(hb) * ENTRY
        ovf_base = post_ptr
        ob = pack_post(gold)
        for i, beat in enumerate(ob):
            writes[word_of(ovf_base + i * ENTRY)] = beat
        post_ptr += len(ob) * ENTRY
        writes[word_of(dir_addr(t, k))] = dir_pack(
            head_base, len(collide), 1, EPOCH, ovf_base, len(gold)
        )

    emit = collide + gold  # CAND_CAP=64 > 36
    wr_i = sorted(writes)
    lines = ["// generated by gen_xsim_ovf.py — do not hand-edit"]
    lines.append(f"localparam int unsigned G_N_WR = {len(wr_i)};")
    lines.append("localparam int G_WR_I [0:G_N_WR-1] = '{")
    lines.append("  " + ", ".join(str(i) for i in wr_i) + "};")
    lines.append("localparam logic [127:0] G_WR_D [0:G_N_WR-1] = '{")
    lines.append("  " + ", ".join(f"128'h{writes[i]:032X}" for i in wr_i) + "};")
    lines.append(f"localparam int unsigned G_QLEN = {len(q['text'])};")
    lines.append(f"localparam logic [8*48-1:0] G_QBYTES = 384'h{pack_text(q['text']):096X};")
    lines.append(f"localparam int unsigned G_ULEN = {len(unk['text'])};")
    lines.append(f"localparam logic [8*48-1:0] G_UBYTES = 384'h{pack_text(unk['text']):096X};")
    for i, name in enumerate(("K0", "K1", "K2", "K3")):
        lines.append(f"localparam logic [15:0] G_{name} = 16'h{q['k'][i]:04X};")
        lines.append(f"localparam logic G_V{i} = 1'b{q['v'][i]};")
    lines.append(f"localparam int unsigned G_N_EMIT = {len(emit)};")
    lines.append(
        "localparam logic [19:0] G_EMIT [0:G_N_EMIT-1] = '{"
        + ", ".join(f"20'h{x:05X}" for x in emit)
        + "};"
    )
    lines.append(f"localparam int unsigned G_N_GOLD = {len(gold)};")
    lines.append(
        "localparam logic [19:0] G_GOLD [0:G_N_GOLD-1] = '{"
        + ", ".join(f"20'h{x:05X}" for x in gold)
        + "};"
    )
    (BAG / "ovf_gold.svh").write_text("\n".join(lines) + "\n", encoding="utf-8")
    meta = {
        "k": q["k"],
        "v": q["v"],
        "packet": {"eid": q["eid"], "iid": q["iid"], "rid": q["rid"], "xid": q["xid"]},
        "collide": collide,
        "gold": gold,
        "emit": emit,
        "n_writes": len(writes),
        "index_head": INDEX_HEAD,
    }
    (BAG / "OVF_GOLDEN.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    print("ASTRA02_OVF_XSIM_GOLD_DONE writes", len(writes), "emit", len(emit))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
